create table public.job_postings (
  id bigint generated by default as identity primary key,
  company_user_id uuid not null references public.company_profiles(user_id) on delete cascade,
  title varchar(150) not null,
  location varchar(200) not null,
  description text,
  status varchar(20) not null default 'pending',
  created_at timestamptz not null default now(),

  constraint job_postings_status_check
    check (status in ('pending', 'approved', 'rejected', 'closed'))
);

create table public.applications (
  id bigint generated by default as identity primary key,
  applicant_user_id uuid not null references public.user_profiles(user_id) on delete cascade,
  job_id bigint not null references public.job_postings(id) on delete cascade,
  status varchar(20) not null default 'pending',
  applied_at timestamptz not null default now(),

  constraint applications_status_check
    check (status in ('pending', 'review', 'interview', 'accepted', 'rejected'))
);

create table public.interviews (
  id bigint generated by default as identity primary key,
  applicant_user_id uuid not null references public.user_profiles(user_id) on delete cascade,
  job_id bigint not null references public.job_postings(id) on delete cascade,
  scheduled_at timestamptz not null,
  status varchar(20) not null default 'scheduled',
  details text,
  created_at timestamptz not null default now(),

  constraint interviews_status_check
    check (status in ('scheduled', 'completed', 'cancelled'))
);


alter table public.job_postings enable row level security;
alter table public.applications enable row level security;
alter table public.interviews enable row level security;


grant select on public.job_postings to authenticated;
grant select on public.applications to authenticated;
grant select on public.interviews to authenticated;


create policy "Applicants can view approved jobs"
on public.job_postings
for select
to authenticated
using (
  status = 'approved'
);


create policy "Applicants can view their own applications"
on public.applications
for select
to authenticated
using (
  applicant_user_id = auth.uid()
);


create policy "Applicants can view their own interviews"
on public.interviews
for select
to authenticated
using (
  applicant_user_id = auth.uid()
);


create policy "Applicants can view approved company profiles"
on public.company_profiles
for select
to authenticated
using (
  review_status = 'approved'
  and exists (
    select 1
    from public.user_profiles
    where user_profiles.user_id = auth.uid()
      and user_profiles.role = 'applicant'
      and user_profiles.is_active = true
  )
);